import { api } from "./oracle.mjs";
import { lua } from "./runtime.mjs";
import fs from "node:fs";
export function geometry(ps) {
  const flags = (g) => ({
    bCoef: g.bCoef,
    collisionGroup: g.cGroup,
    collisionMask: g.cMask,
  });
  return {
    planes: ps.planes.map((g, i) => ({
      id: "ref:plane:" + i,
      ...flags(g),
      normalX: g.normal.x,
      normalY: g.normal.y,
      offset: g.dist,
    })),
    segments: ps.segments.map((g, i) => ({
      id: "ref:segment:" + i,
      ...flags(g),
      x1: g.v0.pos.x,
      y1: g.v0.pos.y,
      x2: g.v1.pos.x,
      y2: g.v1.pos.y,
      bias: g.bias,
      ...(Number.isFinite(g.curveF)
        ? {
            curveF: g.curveF,
            centerX: g.arcCenter.x,
            centerY: g.arcCenter.y,
            arcRadius: g.arcRadius,
            v0NormalX: g.v0Normal.x,
            v0NormalY: g.v0Normal.y,
            v1NormalX: g.v1Normal.x,
            v1NormalY: g.v1Normal.y,
          }
        : { normalX: g.normal.x, normalY: g.normal.y }),
    })),
    vertices: ps.vertices.map((g, i) => ({
      id: "ref:vertex:" + i,
      ...flags(g),
      x: g.pos.x,
      y: g.pos.y,
    })),
  };
}
